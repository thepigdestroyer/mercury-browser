//! The palettes Mercury has, as data.
//!
//! Selectable (owner decision of 22 Nov 2026), in the order a picker lists them; [`signal`] is the
//! default:
//!
//! - [`signal`]: `signal`, paper white and ink black with hard hairlines and one hot pink accent.
//! - [`forest`]: `forest`, sage-green paper by day, a dark forest floor by night, lime-mint accent.
//! - [`abyss`]: `abyss`, sea-glass white by day, a blue-green trench by night, turquoise accent.
//! - [`glacier`]: `glacier`, frosted blue-white by day, steel-blue polar night, vivid cyan accent.
//!
//! In the code but **not selectable** (nothing can switch them on, a hand-edited `settings.json`
//! included):
//!
//! - [`graphite`] and [`midnight`]: two more of the 22 Nov designs the owner did not pick.
//! - [`mercury_b2`]: `mercury-b2`, warm cream and deep violet with the brand's orange; rejected.
//! - [`hermes`]: `hermes`, the chrome's colours from before B2: the regression baseline of the
//!   theme-plumbing pixel gate and the look of a window nobody pushes a palette to.
//!
//! The six 22 Nov palettes are generated by `examples/palette_gen.rs` from a few design tokens
//! (edit a token there and rerun it; the tables are plain literals). Adding a palette is a new
//! module with two exhaustive tables, an entry in `ALL` below, and a run of
//! `cargo test -p mercury-appearance`, whose contrast rules every selectable palette must pass.

pub mod abyss;
pub mod forest;
pub mod glacier;
pub mod graphite;
pub mod hermes;
pub mod mercury_b2;
pub mod midnight;
pub mod signal;

use crate::palette::Palette;

/// Every palette: the default first, then the other selectable ones in picker order, then the ones
/// that cannot be chosen.
static ALL: [Palette; 8] = [
    signal::PALETTE,
    forest::PALETTE,
    abyss::PALETTE,
    glacier::PALETTE,
    graphite::PALETTE,
    midnight::PALETTE,
    mercury_b2::PALETTE,
    hermes::PALETTE,
];

/// Every palette, including the ones a user cannot choose. The default is first.
pub fn all() -> &'static [Palette] {
    &ALL
}

/// The palettes a user may choose, in [`all`] order (which is the order a picker lists them).
pub fn selectable() -> impl Iterator<Item = &'static Palette> {
    ALL.iter().filter(|palette| palette.selectable)
}

/// The palette with this id, selectable or not, or `None`.
///
/// This is for code that needs a palette by name, such as the pixel gate asking for `hermes`.
/// Code that resolves an id a user stored should use [`find_selectable`], so that a
/// hand-edited `settings.json` cannot switch a palette that is not offered on.
pub fn find(id: &str) -> Option<&'static Palette> {
    ALL.iter().find(|palette| palette.id == id)
}

/// The selectable palette with this id, or `None` when there is none or it cannot be chosen.
pub fn find_selectable(id: &str) -> Option<&'static Palette> {
    find(id).filter(|palette| palette.selectable)
}

/// The palette of a new or upgraded profile, and of any stored id this version cannot show:
/// [`signal`]. Its id is [`mercury_settings::DEFAULT_PALETTE`], which `tests/palettes.rs` checks.
pub fn default_palette() -> &'static Palette {
    &ALL[0]
}
